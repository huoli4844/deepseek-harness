type laborTestAuth struct{}

func (laborTestAuth) AuthorizeCustomer(r *http.Request) (CustomerAccess, bool) {
	switch r.Header.Get("Authorization") {
	case "write":
		return CustomerAccess{TenantID: 3, UserID: 5, CanWrite: true}, true
	case "read":
		return CustomerAccess{TenantID: 3, UserID: 5}, true
	default:
		return CustomerAccess{}, false
	}
}

func testLaborHTTP(t *testing.T) *http.ServeMux {
	t.Helper()
	dsn := os.Getenv("DSH_LABOR_TEST_DATABASE_URL")
	if dsn == "" {
		t.Skip("未提供独立工时测试数据库")
	}
	cfg, err := pgxpool.ParseConfig(dsn)
	if err != nil || !net.ParseIP(cfg.ConnConfig.Host).IsLoopback() ||
		!regexp.MustCompile(`^dsh_labor_test(_[0-9]+)?$`).MatchString(cfg.ConnConfig.Database) ||
		len(cfg.ConnConfig.Fallbacks) > 0 {
		t.Fatal("仅可使用命名符合约定且禁用故障转移的回环地址测试库")
	}
	pool, err := pgxpool.NewWithConfig(context.Background(), cfg)
	if err != nil {
		t.Fatal("连接工时测试数据库失败")
	}
	t.Cleanup(pool.Close)
	if _, err := pool.Exec(context.Background(), laborFixture); err != nil {
		t.Fatalf("初始化工时测试数据失败：%v", err)
	}
	migration, err := os.ReadFile("../../../migrations/0003_labor_completion.sql")
	if err != nil {
		t.Fatal(err)
	}
	if _, err := pool.Exec(context.Background(), string(migration)); err != nil {
		t.Fatalf("工时迁移失败：%v", err)
	}
	checkLaborMigration(t, pool)
	mux := http.NewServeMux()
	RegisterLabor(mux, application.New(repository.New(pool)), laborTestAuth{})
	return mux
}

func checkLaborMigration(t *testing.T, pool *pgxpool.Pool) {
	t.Helper()
	ctx := context.Background()
	var note, updateNote string
	if err := pool.QueryRow(ctx, `SELECT col_description(a.attrelid,a.attnum), col_description(b.attrelid,b.attnum)
		FROM pg_attribute a JOIN pg_attribute b ON b.attrelid=a.attrelid AND b.attname='updated_at'
		WHERE a.attrelid='public.fin_labor_hours'::regclass AND a.attname='completion_status'`).Scan(&note, &updateNote); err != nil {
		t.Fatal(err)
	}
	for _, fragment := range []string{"blocked=已阻塞", "cancelled=已取消", "completed=已完成", "in_progress=进行中", "pending=待处理/待审批", "NULL"} {
		if !strings.Contains(note, fragment) {
			t.Fatalf("工时完成状态备注缺少 %q", fragment)
		}
	}
	if !strings.Contains(updateNote, "保留原值") {
		t.Fatal("更新时间备注缺少提交规则")
	}
	if _, err := pool.Exec(ctx, "UPDATE public.fin_labor_hours SET completion_status='invalid' WHERE id=1"); err == nil {
		t.Fatal("数据库应拒绝越界的工时完成状态")
	}
}

func laborRequest(t *testing.T, mux *http.ServeMux, method, path, auth, body string, status int, contains ...string) string {
	t.Helper()
	r := httptest.NewRequest(method, path, strings.NewReader(body))
	r.Header.Set("Authorization", auth)
	r.Header.Set("X-Active-Tenant", "未经验证的租户")
	w := httptest.NewRecorder()
	mux.ServeHTTP(w, r)
	if w.Code != status {
		t.Fatalf("%s %s 返回 %d，预期 %d，响应 %s", method, path, w.Code, status, w.Body)
	}
	for _, expected := range contains {
		if !strings.Contains(w.Body.String(), expected) {
			t.Fatalf("响应缺少 %q：%s", expected, w.Body)
		}
	}
	return w.Body.String()
}

func TestLaborProjectFilteringAndOwnership(t *testing.T) {
	mux := testLaborHTTP(t)
	const path = projectsPath + "/OWN/labor-hours"
	const draft = `{"task_id":1,"work_date":"2026-11-24","hours":"1.50","work_type":"meeting","description":"项目会","completion_status":"completed"}`
	laborRequest(t, mux, "GET", projectsPath+"?keyword=own", "read", "", 200, `"total":1`, `"code":"OWN"`)
	laborRequest(t, mux, "GET", projectsPath+"?keyword=foreign", "read", "", 200, `"items":[],"total":0`)
	laborRequest(t, mux, "GET", projectsPath+"?keyword=old", "read", "", 200, `"items":[],"total":0`)
	laborRequest(t, mux, "GET", projectsPath+"/OWN/tasks?keyword=本项目&page_size=1", "read", "", 200,
		`"code":"T1"`, `"status":"in_progress"`, `"total":1`)
	laborRequest(t, mux, "GET", projectsPath+"/OWN/tasks", "read", "", 200, `"total":1`)
	laborRequest(t, mux, "GET", projectsPath+"/FOREIGN/tasks", "read", "", 404)
	laborRequest(t, mux, "GET", path+"?status=approved&date_from=2026-11-23&date_to=2026-11-29&sort_by=hours&sort_dir=asc&page_size=1",
		"read", "", 200, `"total":2,"archive_total":5`, `"hours":"2.00"`, `"page_size":1`)
	laborRequest(t, mux, "GET", path+"?status=approved&date_from=2026-11-23&date_to=2026-11-29&sort_by=hours&sort_dir=asc&page_size=1&page=2",
		"read", "", 200, `"total":2`, `"hours":"10.00"`)
	laborRequest(t, mux, "GET", path+"?status=approved&sort_by=work_date&sort_dir=asc&page_size=1&page=3", "read", "", 200,
		`"work_date":null`, `"work_type":"production"`, `"completion_status":null`)
	laborRequest(t, mux, "GET", path+"?status=draft&user_id=7", "write", "", 200, `"items":[],"total":0`)
	laborRequest(t, mux, "GET", path+"?date_from=2026-11-30&date_to=2026-11-29", "read", "", 400)
	laborRequest(t, mux, "GET", path+"?sort_by=hourly_rate&sort_dir=asc", "read", "", 400)
	laborRequest(t, mux, "GET", path+"?status=approved&status=draft", "read", "", 400)
	laborRequest(t, mux, "GET", projectsPath+"/FOREIGN/labor-hours", "read", "", 404)
	laborRequest(t, mux, "POST", path, "", draft, 401)
	laborRequest(t, mux, "POST", path, "read", draft, 403)
	laborRequest(t, mux, "POST", path, "write", strings.Replace(draft, `"task_id":1`, `"user_id":7`, 1), 400)
	for _, invalidHours := range []string{"0", "1.123", "1000", "-1", "null"} {
		laborRequest(t, mux, "POST", path, "write", strings.Replace(draft, `"1.50"`, invalidHours, 1), 400)
	}
	laborRequest(t, mux, "POST", path, "write", strings.Replace(draft, `"completed"`, `"submitted"`, 1), 400)
	for _, wrongTask := range []string{"2", "3", "4"} {
		laborRequest(t, mux, "POST", path, "write", strings.Replace(draft, `"task_id":1`, `"task_id":`+wrongTask, 1), 404)
	}
	laborRequest(t, mux, "PUT", path+"/4", "write", draft, 404)
	laborRequest(t, mux, "PUT", path+"/7", "write", draft, 200, `"status":"draft"`, `"can_edit":true`)
	laborRequest(t, mux, "POST", path+"/8/submit", "write", "", 400)
	created := laborRecord(t, laborRequest(t, mux, "POST", path, "write", draft, 200,
		`"id":9`, `"user_id":5`, `"hours":"1.50"`, `"can_submit":true`, `"completion_status":"completed"`))
	edited := laborRecord(t, laborRequest(t, mux, "PUT", path+"/9", "write", strings.Replace(draft, `"1.50"`, `2.25`, 1), 200,
		`"hours":"2.25"`, `"completion_status":"completed"`))
	submitted := laborRecord(t, laborRequest(t, mux, "POST", path+"/9/submit", "write", "", 200,
		`"status":"submitted"`, `"submitted_at":"`, `"can_edit":false`, `"completion_status":"completed"`))
	if !edited.UpdatedAt.After(created.UpdatedAt) || !submitted.UpdatedAt.Equal(edited.UpdatedAt) {
		t.Fatal("工时编辑应更新修改时间，仅提交应保留原值")
	}
	laborRequest(t, mux, "GET", path+"?sort_by=completion_status&sort_dir=asc&page_size=1", "write", "", 200,
		`"completion_status":"completed"`)
	laborRequest(t, mux, "POST", path+"/9/submit", "write", "", 409)
	laborRequest(t, mux, "PUT", path+"/9", "write", draft, 409)
	laborRequest(t, mux, "PATCH", path, "write", draft, 405)
	laborRequest(t, mux, "GET", path+"/unknown/route", "read", "", 404)
}

func laborRecord(t *testing.T, body string) domain.Record {
	t.Helper()
	var payload struct{ Data domain.Record }
	if err := json.Unmarshal([]byte(body), &payload); err != nil {
		t.Fatal(err)
	}
	return payload.Data
}
